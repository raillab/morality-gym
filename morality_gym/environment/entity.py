class AgentEntity(HarmableEntity):
    def __init__(
            self,
            name: Hashable,
            size: float,
            pos: Optional[np.ndarray] = None,
            movable: bool = False,
            collide: bool = True,
            mass: float = 1.0,
            max_speed: Optional[float] = None,
            speediness: float = 1.0,  # Modifier to control signal impacting speed of agent,
            speediness_harm_mod = 0.5,  # Modifier on speediness when minorly harmed
            minor_harm_threshold: float = 1.0,  # TODO: Get correct no
            major_harm_threshold: float = 2.0  # TODO: Get correct no
    ):
        super().__init__(
            name, size,
            pos=pos,
            movable=movable, collide=collide, actable=True,
            mass=mass, max_speed=max_speed,
            minor_harm_threshold=minor_harm_threshold, major_harm_threshold=major_harm_threshold
        )

        # Action is an (x, y) control signal
        self.action: Optional[np.ndarray] = None

        if speediness <= 0:
            raise ValueError(f"Invalid value for speediness={speediness}. speediness must satisfy speediness>0")

        self.speediness: float = speediness
        self._init_speediness = speediness

        if not 0 <= speediness_harm_mod <= 1:
            raise ValueError(f"Invalid value for speediness_harm_mod={speediness_harm_mod}. "
                             f"speediness_harm_mod must satisfy 0<=speediness_harm_mod<=1")
        self.speediness_harm_mod = speediness_harm_mod


        # self.minor_harm_threshold = minor_harm_threshold
        # self.major_harm_threshold = major_harm_threshold
        #
        # self.current_harm = Harm.NoHarm

        self.is_terminated = False

    def reset_harm(self):
        super().reset_harm()
        self.speediness = self._init_speediness

    def set_harm(self, harm: Harm, harm_source: HarmSource):
        if harm != self.current_harm:
            super().set_harm(harm, harm_source)

            # Augment speed if minorly harmed
            if harm == Harm.MinorHarm:
                self.speediness = self.speediness * self.speediness_harm_mod

