class HarmableEntity(Entity):
    def __init__(
            self,
            name: Hashable,
            size: float,
            pos: Optional[np.ndarray] = None,
            movable: bool = False,
            collide: bool = False,
            actable: bool = False,
            # density: float = 25.0,
            mass: float = 1.0,
            max_speed: Optional[float] = None,
            minor_harm_threshold: float = 1.0,  # TODO: Get correct no
            major_harm_threshold: float = 2.0  # TODO: Get correct no
    ):
        super().__init__(
            name, size,
            pos=pos, movable=movable, collide=collide, actable=actable, mass=mass, max_speed=max_speed
        )

        self.minor_harm_threshold = minor_harm_threshold
        self.major_harm_threshold = major_harm_threshold

        self.current_harm = Harm.NoHarm
        self.harm_source: HarmSource = HarmSource.NoHarmSource

        self.is_harmable = True  # E.g. one reason is that it cannot be further harmed if current_harm = MajorHarm
        self.just_harmed = False

        self.is_harmed = False
        self.is_min_harmed = False
        self.is_maj_harmed = False
        self.is_min_env_harmed = False
        self.is_maj_env_harmed = False
        self.is_min_rob_harmed = False
        self.is_maj_rob_harmed = False

        # Force applied by env
        self.force_env: Optional[np.ndarray] = np.zeros(2, dtype=float)
        # Force applied by robot
        self.force_robot: Optional[np.ndarray] = np.zeros(2, dtype=float)

        # # 'External' force acting on entity along (x,y) - used for harm calc
        # self.force_ext: Optional[np.ndarray] = np.zeros(2, dtype=float)
        # # 'Internal' Force acting on entity along (x,y)
        # self.force_int: Optional[np.ndarray] = np.zeros(2, dtype=float)

    def set_harm(self, harm: Harm, harm_source: HarmSource):
        # Do nothing and return early if current_harm won't be changed
        if harm == self.current_harm:
            return

        if harm_source not in HarmSource.__members__.values():
            raise ValueError(f"Invalid value for harm_source={harm_source}. harm_source must satisfy harm_source in {HarmSource.__members__}")

        if harm == Harm.NoHarm:
            self.reset_harm()
        elif harm == Harm.MinorHarm:
            self.current_harm = harm
            self.harm_source = harm_source
            self.just_harmed = True

            self.is_harmed = True
            self.is_min_harmed = True
            # Assuming valid harm_source
            if harm_source == HarmSource.Env:
                self.is_min_env_harmed = True
            else:
                self.is_min_rob_harmed = True
        elif harm == Harm.MajorHarm:
            self.current_harm = harm
            self.harm_source = harm_source

            self.movable = False
            self.is_harmable = False
            self.actable = False

            self.just_harmed = True

            self.is_harmed = True
            self.is_maj_harmed = True
            if harm_source == HarmSource.Env:
                self.is_maj_env_harmed = True
            else:
                self.is_maj_rob_harmed = True
        else:
            raise ValueError(f"Invalid value for harm={harm}. harm must satisfy harm in {Harm.__members__}")



    ###############
    # -- RESET -- #
    ###############
    def reset_harm(self):
        self.current_harm = Harm.NoHarm
        self.harm_source = HarmSource.NoHarmSource

        self.is_harmed = False
        self.is_min_harmed = False
        self.is_maj_harmed = False
        self.is_min_env_harmed = False
        self.is_maj_env_harmed = False
        self.is_min_rob_harmed = False
        self.is_maj_rob_harmed = False

        self.is_harmable = True
        self.just_harmed = False

        self.movable = self._init_movable
        self.collide = self._init_collide
        self.actable = self._init_actable

    def reset_force(self):
        super().reset_force()
        self.force_env = np.zeros(2, dtype=float)
        self.force_robot = np.zeros(2, dtype=float)
