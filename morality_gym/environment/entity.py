class Harm(IntEnum):
    NoHarm = 0
    MinorHarm = 1
    MajorHarm = 2


class HarmSource(IntEnum):
    NoHarmSource = 0
    Robot = 1
    Env = 2


# ENTITY #
class Entity:
    def __init__(
            self,
            name: Hashable,
            size: float,
            pos: Optional[np.ndarray] = None,
            movable: bool = False,
            collide: bool = False,
            actable: bool = False,
            density: float = 25.0,
            mass: float = 1.0,
            max_speed: Optional[float] = None
    ):
        self.name = name
        self.size = size

        self.movable = movable
        self.collide = collide
        self.actable = actable

        self.events = []

        # Init values - store in case they change and need to be reinit
        self._init_movable = movable
        self._init_collide = collide
        self._init_actable = actable
        self._init_pos = None if pos is None else pos.copy()

        self.density = density
        self.max_speed = max_speed
        self.mass = mass

        self.accel = None  # ?

        self.pos: Optional[np.ndarray] = pos
        self.vel: Optional[np.ndarray] = np.zeros(2, dtype=float)

        # Total force acting on entity along (x,y)
        self.force: Optional[np.ndarray] = np.zeros(2, dtype=float)
        # 'External' force acting on entity along (x,y)
        self.force_ext: Optional[np.ndarray] = np.zeros(2, dtype=float)
        # 'Internal' force acting on entity along (x,y) - force generated by agent
        self.force_int: Optional[np.ndarray] = np.zeros(2, dtype=float)

        self.collisions: Set[Tuple[Entity, str]] = set()
        # self.state = EntityState()

    def reset(self):
        self.movable = self._init_movable
        self.collide = self._init_collide
        self.actable = self._init_actable

        self.reset_force()

        self.collisions = set()

    def reset_force(self):
        self.force = np.zeros(2, dtype=float)
        self.force_ext = np.zeros(2, dtype=float)
        self.force_int = np.zeros(2, dtype=float)

    @staticmethod
    def force_magn(force: np.ndarray) -> float:
        return float(np.linalg.norm(force))

    def __hash__(self):
        return self.name

    def __repr__(self):
        class_name = self.__class__.__name__
        return f"{class_name} - name = {self.name}"

    @property
    def init_pos(self):
        return self._init_pos.copy() if self._init_pos is not None else None



