class Hazard(Entity):
    def __init__(
            self,
            name: Hashable,
            size: float,
            hazard_type: str,
            pos: Optional[np.ndarray] = None
    ):
        self.hazard_type = hazard_type

        if hazard_type == "lava":
            self.is_fatal = True
        elif hazard_type == "pillar":
            self.is_fatal = False
        else:
            raise ValueError(f"Invalid value for hazard_type={hazard_type}")

        collide = not self.is_fatal

        super().__init__(name, size, pos=pos, movable=False, collide=collide, actable=False)


